const setupCommand = `git clone https://github.com/D1bakar/Dokimana.git
cd Dokimana
npm ci
npm run build
npm start -- doctor`

const quickstartCommand = `npm ci && npm run build && npm start -- scan \\
  --repo . \\
  --old fixtures/stripe-old.json \\
  --new fixtures/stripe-new.json \\
  --old-version fixture-old \\
  --new-version fixture-new \\
  --json dokimana-impact.json \\
  --markdown dokimana-evidence.md`

function Command({ children }: { children: string }) {
  return (
    <pre className="command">
      <code>{children}</code>
    </pre>
  )
}

function TerminalDemo({ run }: { run: ExampleRunData }) {
  const terminalText = [
    ...run.commands.map((command) => `$ ${command}`),
    ...run.output,
  ].join('\n')

  return (
    <section id="captured-run" aria-labelledby="captured-run-title">
      <h2 id="captured-run-title">Captured run</h2>
      <p>
        This block shows a supported CLI command and the output captured from a local run. The
        checked-in JSON is generated by CI; no output is typed in by hand.
      </p>
      <figure className="terminal-demo">
        <figcaption>Terminal output · generated sample</figcaption>
        <pre className="terminal-output">
          <code>{terminalText}</code>
        </pre>
      </figure>
      {run.output.length === 0 && (
        <p className="data-note">
          {run.note ?? 'No captured output is published yet. The generated sample will appear here.'}
        </p>
      )}
    </section>
  )
}

